#!/usr/bin/env node
/**
 * Regenerates `src/db/migrations/bundle.ts`: the migrations as the phone imports them.
 *
 *   npx drizzle-kit generate && node src/db/tools/bundle-migrations.mjs
 *
 * Why a generated TypeScript module instead of drizzle-kit's `driver: 'expo'` output: that output
 * imports `.sql` files, which needs a Babel inline-import plugin and a Metro `sourceExts` change —
 * config outside `src/db`, and one more thing Jest has to be taught. Embedding the SQL as string
 * literals needs none of it. `src/db/migrations.test.ts` fails when this file is stale.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const folder = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'migrations');
const journal = JSON.parse(fs.readFileSync(path.join(folder, 'meta', '_journal.json'), 'utf8'));

/** A JS string literal with every character above `~` escaped, so the bundle is plain ASCII. */
function literal(text) {
  const json = JSON.stringify(text);
  let out = '';
  for (let i = 0; i < json.length; i += 1) {
    const code = json.charCodeAt(i);
    out += code > 0x7e ? `\\u${code.toString(16).padStart(4, '0')}` : json.charAt(i);
  }
  return out;
}

const entries = journal.entries.map((entry) => {
  const key = `m${String(entry.idx).padStart(4, '0')}`;
  const sql = fs.readFileSync(path.join(folder, `${entry.tag}.sql`), 'utf8');
  return `    /** ${entry.tag} */\n    ${key}: ${literal(sql)},`;
});

const source = `/**
 * GENERATED by src/db/tools/bundle-migrations.mjs from the drizzle-kit output in this folder.
 * Do not edit. Regenerate after every \`drizzle-kit generate\`; src/db/migrations.test.ts fails if stale.
 *
 * This is what drizzle's expo-sqlite migrator runs on the phone.
 */
import journal from './meta/_journal.json';

const migrations = {
  journal,
  migrations: {
${entries.join('\n')}
  },
};

export default migrations;
`;

const out = path.join(folder, 'bundle.ts');
fs.writeFileSync(out, source);
console.log(`bundled ${journal.entries.length} migration(s) into ${path.relative(process.cwd(), out)}`);
